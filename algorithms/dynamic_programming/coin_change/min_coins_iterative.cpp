#include <iostream>
#include <algorithm>

# define INF 2147483647
using namespace std;

/*
 *  Задача о размене монет.
 *  Переменные:
 *  coins - номиналы монет.
 *  SUM - сумма для размена.
 *  dp[SUM+1] - массив для хранения предыдущих решений.
 *  Память: O(n)
 *  Время: O(n * size(coins))
 */
const int coins[3] = {1,3,4}; // Номиналы монет
const int SUM = 10; // Сумма для размена

int main() {
    int dp[SUM+1] = {0}; // Добавляем базовый случай dp[0] = 0

    for (int i = 1; i <= SUM ; ++i) { // Начинаем разменивать с единицы
        dp[i] = INF; // Ставим огромное значение, далее ищем оптимальные решения
        for (const int c: coins) { // Range-based for C++
            if (i - c < 0) break; // Номиналы отсортированы, решение можно прервать 
            if (dp[i-c] != INF) { // Защита от переполнения(помогает при наличии недостижимых сумм)
                dp[i] = min(dp[i], dp[i-c] + 1); // Или не берем или берем
            }
        }
    }
    cout << dp[SUM] << endl;
}
